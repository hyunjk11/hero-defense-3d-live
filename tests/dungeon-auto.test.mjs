import assert from 'node:assert/strict';
import { autoBlessChoice, wantAutoJoint, loadDungeonAuto, saveDungeonAuto } from '../src/dungeon/auto.js';
import { BLESS } from '../src/data/dungeon.js';

const hero = (cls, hp = 100, extra = {}) => ({ cls, hp, max: 100, dead: 0, ult: 100, ...extra });
const party = [hero('warrior'), hero('mage'), hero('archer'), hero('fighter')];
const foe = extra => ({ hp: 200, dead: false, E: {}, ...extra });
assert.equal(autoBlessChoice(['crit', 'heal', 'might'], {}, party.map(h => ({ ...h, hp: 10 }))), 'heal');
assert.equal(autoBlessChoice(['heal', 'might'], {}, party), 'might', 'do not waste healing at full health');
assert.equal(autoBlessChoice(['heal', 'might'], {}, [hero('mage', 35)], .5), 'might', 'pending recovery is included in multi-pick decisions');
assert.equal(autoBlessChoice(['heal', 'might'], {}, [hero('mage', 35)], .5, .5), 'heal', 'curse reduces both rest and pending recovery');
assert.equal(autoBlessChoice(['heal', 'crit'], {}, [hero('mage', 0, { dead: 100 })]), 'heal', 'revived heroes need healing');
assert.equal(autoBlessChoice(['ranged', 'caster', 'heal'], {}, [hero('mage')]), 'caster', 'pick a blessing for the actual party');
assert.equal(autoBlessChoice(['missing', 'might', 'haste'], { might: 3 }, party), 'haste');
assert.equal(autoBlessChoice(BLESS.map(b => b.id), Object.fromEntries(BLESS.map(b => [b.id, b.max])), party), null);
assert.equal(autoBlessChoice([], {}, party), null);
assert.equal(autoBlessChoice(['ranged', 'tank'], {}, [hero('mage')]), null);
assert.equal(wantAutoJoint(party, []), false, 'no empty-room casts');
assert.equal(wantAutoJoint(party, [foe()]), false, 'save gauge for a threatening fight');
assert.equal(wantAutoJoint(party, Array.from({ length: 4 }, () => foe())), true);
assert.equal(wantAutoJoint(party, [foe({ E: { boss: true } })]), true);
assert.equal(wantAutoJoint(party, [foe({ elite: true })]), true);
assert.equal(wantAutoJoint([hero('mage', 20)], [foe()]), true, 'emergency use');
assert.equal(wantAutoJoint([hero('mage', 20, { ult: 99 })], [foe({ E: { boss: true } })]), false);
assert.equal(wantAutoJoint([hero('mage', 0, { dead: 100 })], [foe({ E: { boss: true } })]), false);
assert.equal(wantAutoJoint(party, [foe({ dead: true, E: { boss: true } }), foe({ state: 'spawn', E: { boss: true } })]), false);
const values = new Map();
globalThis.localStorage = { getItem: k => values.get(k), setItem: (k, v) => values.set(k, v) };
assert.equal(loadDungeonAuto(), false);
saveDungeonAuto(true); assert.equal(loadDungeonAuto(), true);
saveDungeonAuto(false); assert.equal(loadDungeonAuto(), false);
globalThis.localStorage = { getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); } };
assert.equal(loadDungeonAuto(), false); assert.doesNotThrow(() => saveDungeonAuto(true));
console.log('PASS dungeon all-auto decisions and preference');
