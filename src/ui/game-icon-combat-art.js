function enamels(body){
  const colors=new Map();
  body=body.replace(/ fill="(#[a-f0-9]{6})"/gi,(attr,color)=>{
    const ch=[1,3,5].map(i=>parseInt(color.slice(i,i+2),16));
    if(Math.max(...ch)<120)return attr;
    if(!colors.has(color))colors.set(color,'enamel-'+colors.size);
    return ' fill="url(#'+colors.get(color)+')"';
  });
  let defs='';
  for(const [hex,id] of colors){
    const pale=Math.min(...[1,3,5].map(i=>parseInt(hex.slice(i,i+2),16)))>158;
    defs+='<linearGradient id="'+id+'" x1="0%" y1="4%" x2="87%" y2="99%"><stop offset="0" stop-color="'+tone(hex,[255,244,197],pale?.48:.30)+'"/><stop offset=".49" stop-color="'+hex+'"/><stop offset="1" stop-color="'+tone(hex,[88,47,104],pale?.22:.30)+'"/></linearGradient>';
  }
  return defs?'<defs>'+defs+'</defs>'+body:body;
}
